import SwiftUI
import MapKit
/// Reusable display for a location
struct LocationCard: View {
    /// MapItem to display
    let location: MapItem
    
    /// Selected places binding which is modified by this view's controls
    var selectedPlaces: Binding<[MapItem]>?
    
    /// Places to remove binding which is modified by this view's controls. Associated with GeminiViewModel
    var placesToRemove: Binding<[String]>?

    
    /// Takes a ``MapItem`` to be displayed.
    /// Optionally, takes a Binding for ``selectedPlaces`` when ``location`` can be added or deleted from a ``Trip``.
    /// Optionally, takes  a binding for ``placesToRemove`` when ``location`` is to be regenerated in an AI generated trip
    init(location: MapItem,
         selectedPlaces: Binding<[MapItem]>? = nil,
         placesToRemove: Binding<[String]>? = nil,
    ) {
        self.location = location
        self.selectedPlaces = selectedPlaces
        self.placesToRemove = placesToRemove
    }
    
    /// View-specific state to detect if location is part of ``Trip``.
    var isSelected: Bool {
        if let selectedPlaces {
            return selectedPlaces.wrappedValue.contains(where: {
                $0.identifier == location.identifier
            })
        }
        return false
    }
    
    // MARK: Whether a location is selected for removal in an AI Generated trip
    var isSelectedForRemoval: Bool {
        if let placesToRemove {
            return placesToRemove.wrappedValue.contains(where: {
                $0 == location.identifier
            })
        }
        
        return false
    }
    
    var body: some View {
        HStack(spacing: 16) {
            
            // MARK: Location pin SF Symbol icon
            Image(systemName: "mappin.circle.fill")
                .font(.title2)
                .foregroundStyle(.gray)
                .accessibilityHidden(true)
            
            // MARK: Place information
            VStack(alignment: .leading, spacing: 4) {
                Text(location.mkMapItem.name ?? "No name")
                    .font(.headline)
                    .foregroundStyle(.primary)
                    .fixedSize(horizontal: false, vertical: true)

                Text(location.mkMapItem.address?.shortAddress ?? "No address")
                    .font(.subheadline)
                    .foregroundStyle(.primary)
                    .fixedSize(horizontal: false, vertical: true)
                    
            }
            
            Spacer()
            
            // MARK: "Add" / "Remove" button
            if (selectedPlaces != nil) {
                Button {
                    if let selectedPlaces {
                        isSelected ? selectedPlaces.wrappedValue.removeAll(where: { $0.identifier == location.identifier}) : selectedPlaces.wrappedValue.append(location)                        
                    }
                } label: {
                    Image(systemName: isSelected ? "minus" : "plus")
                        .bold()
                        .foregroundStyle(.white)
                        .frame(width: 32, height: 32)
                        .background(isSelected ? Color.red : Color.accentColor)
                        .clipShape(Circle())
                }.accessibilityLabel(isSelected ? "Remove  location \(location.mkMapItem.name ?? "") from the trip." : "Add location \(location.mkMapItem.name ?? "") to the trip."  )
                    .accessibilityIdentifier("add.remove." + (location.mkMapItem.name ?? ""))
            }
            
            // MARK: Selection for adding/removing from places to remove in AI Generated trip
            if (placesToRemove != nil) {
                Button("",
                       systemImage: isSelectedForRemoval ? "checkmark.circle.fill" : "circle"
                ) {
                    if let placesToRemove{
                        isSelectedForRemoval ? placesToRemove.wrappedValue.removeAll(where: { $0 == location.identifier}) : placesToRemove.wrappedValue.append(location.identifier)
                    }
                }
                .font(.title)
                .foregroundColor(isSelectedForRemoval ?
                    .dora : .gray
                )
                .accessibilityIdentifier("\(location.identifier).check")
                .accessibilityLabel(isSelectedForRemoval ? "Deselect this place to be regenerated by AI" : "Select this place to be regenerated by AI")
            }
        }
        .padding()
        .background(
            RoundedRectangle(cornerRadius: 16)
                .fill(Color(.systemBackground))
        )
        // Card border
        .overlay(
            RoundedRectangle(cornerRadius: 16)
                .stroke(Color(.systemGray4), lineWidth: 1)
        )
    }
}

